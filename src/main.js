function resolveSelectedVoice() {
  const key = `${state.language}:${state.voiceProfile}`;
  const cachedVoiceURI = voiceCache.get(key);
  const cachedVoice = state.voices.find((voice) => voice.voiceURI === cachedVoiceURI);
  if (cachedVoice) return cachedVoice;

  const voice = chooseVoiceForProfile();
  if (voice) {
    voiceCache.set(key, voice.voiceURI);
    state.selectedVoiceURI = voice.voiceURI;
  }
  return voice;
}

function chooseVoiceForProfile() {
  if (!state.voices.length) return null;
  const base = languageBase();
  const exactLanguage = state.language.toLowerCase();
  const profile = voiceProfiles[state.voiceProfile] || voiceProfiles.woman;
  const candidates = state.voices.filter((voice) => {
    const name = voice.name.toLowerCase();
    return voice.lang.toLowerCase().startsWith(base) && !unclearVoiceNames.test(name);
  });
  const profileCandidates = filterVoicesForProfile(candidates, profile);
  if (base === "ar" && profile.targetGender === "female" && candidates.length && !profileCandidates.length) {
    return null;
  }
  const fallbackProfileVoices = filterVoicesForProfile(state.voices, profile);
  const pool = profileCandidates.length
    ? profileCandidates
    : candidates.length
      ? candidates
      : fallbackProfileVoices.length
        ? fallbackProfileVoices
        : state.voices;

  return pool
    .map((voice) => ({ voice, score: scoreVoice(voice, exactLanguage, base, profile) }))
    .sort((a, b) => b.score - a.score)[0]?.voice || null;
}

function filterVoicesForProfile(voices, profile) {
  if (profile.targetGender === "female") {
    const femaleVoices = voices.filter((voice) => femaleVoiceNames.test(voice.name));
    if (femaleVoices.length) return femaleVoices;
    return voices.filter((voice) => !maleVoiceNames.test(voice.name) && !unclearVoiceNames.test(voice.name));
  }
  if (profile.targetGender === "male") {
    const maleVoices = voices.filter((voice) => maleVoiceNames.test(voice.name));
    if (maleVoices.length) return maleVoices;
    return voices.filter((voice) => !femaleVoiceNames.test(voice.name) && !unclearVoiceNames.test(voice.name));
  }
  return voices;
}

function scoreVoice(voice, exactLanguage, base, profile) {
  const name = voice.name.toLowerCase();
  const lang = voice.lang.toLowerCase();
  const preferredNames = getPreferredVoiceNames();
  const preferredIndex = preferredNames.findIndex((preferredName) => voiceNameMatches(voice, preferredName));
  let score = 0;
  if (preferredIndex >= 0) score += 1000 - preferredIndex * 20;
  if (lang === exactLanguage) score += 180;
  else if (lang.startsWith(base)) score += 130;
  if (voice.localService) score += 20;
  if (voice.default) score += 6;
  if (unclearVoiceNames.test(name)) score -= 500;
  if (highQualityVoiceNames.test(voice.name)) score += 120;
  if (name.includes("compact")) score -= 80;

  profile.keywords.forEach((keyword, index) => {
    if (name.includes(keyword)) score += 22 - Math.min(index, 14);
  });

  if (profile.targetGender === "male") {
    if (maleVoiceNames.test(voice.name)) score += 180;
    if (femaleVoiceNames.test(voice.name)) score -= 500;
  }
  if (profile.targetGender === "female") {
    if (femaleVoiceNames.test(voice.name)) score += 180;
    if (maleVoiceNames.test(voice.name)) score -= 500;
  }
  return score;
}

function getPreferredVoiceNames() {
  const exact = preferredVoiceNames[state.language]?.[state.voiceProfile];
  if (exact) return exact;
  return preferredVoiceNames[languageBase()]?.[state.voiceProfile] || [];
}

function voiceNameMatches(voice, preferredName) {
  const normalize = (value) =>
    String(value)
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase();
  return normalize(voice.name) === normalize(preferredName) || normalize(voice.voiceURI) === normalize(preferredName);
}

function warmSelectedVoice() {
  if (!("speechSynthesis" in window) || !state.voices.length) return;
  const key = `${state.language}:${state.voiceProfile}`;
  if (warmedVoiceKeys.has(key)) return;

  const utterance = createSpeechUtterance(".", "word");
  utterance.volume = 0;
  utterance.onend = () => {
    warmupPending = false;
    warmedVoiceKeys.add(key);
  };
  utterance.onerror = () => {
    warmupPending = false;
  };

  warmupPending = true;
  window.speechSynthesis.speak(utterance);
}

