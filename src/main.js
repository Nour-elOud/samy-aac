function speakAddedWord(label) {
  const phrase = getSpeechText(label);
  if (!phrase) return;
  if (shouldUseAudioTts()) {
    speakText(phrase, { interrupt: true, mode: "word" });
    return;
  }
  const chunks = phrase.split(/\s+/).filter(Boolean);
  (chunks.length ? chunks : [phrase]).forEach((chunk) => {
    speakText(chunk, { interrupt: false, mode: "word" });
  });
}

function speakText(text, { interrupt = false, mode = "word" } = {}) {
  const phrase = String(text || "").trim();
  if (!phrase) return;
  const useAudioTts = shouldUseAudioTts();

  if (useAudioTts && isDuplicateAudioSpeech(phrase, mode)) return;
  if (warmupPending || interrupt) {
    stopSpeech({ resetDuplicateMemory: !useAudioTts });
  }

  if (useAudioTts) {
    audioQueue = playAudioTts(phrase, mode, speechRunId);
    return;
  }

  speakWithSpeechSynthesis(phrase, mode);
}

function speakWithSpeechSynthesis(text, mode = "word") {
  if (!("speechSynthesis" in window)) return;
  const utterance = createSpeechUtterance(text, mode);
  window.speechSynthesis.speak(utterance);
}

function shouldUseAudioTts() {
  return state.voiceProfile === "woman" && Boolean(audioTtsProfiles[state.language]);
}

function isDuplicateAudioSpeech(text, mode) {
  const now = performance.now();
  const key = `${state.language}:${state.voiceProfile}:${mode}:${text}`;
  const isDuplicate = lastAudioSpeech.key === key && now - lastAudioSpeech.time < 1200;
  lastAudioSpeech = { key, time: now };
  return isDuplicate;
}

function queueAudioTts(text, mode, runId) {
  const phrase = String(text || "").trim();
  if (!phrase) return;
  audioQueue = audioQueue
    .then(() => {
      if (runId !== speechRunId) return undefined;
      return playAudioTts(phrase, mode, runId);
    })
    .catch(() => {
      if (runId !== speechRunId) return undefined;
      return playAudioTts(phrase, mode, runId);
    });
}

function playAudioTts(text, mode, runId) {
  const url = getAudioTtsUrl(text);
  if (runId !== speechRunId) return Promise.resolve();
  if (!url) {
    speakWithSpeechSynthesis(text, mode);
    return Promise.resolve();
  }
  return new Promise((resolve) => {
    const audio = new Audio(url);
    let playbackStarted = false;
    currentAudio = audio;
    audio.preload = "auto";
    audio.volume = 1;
    audio.onplaying = () => {
      playbackStarted = true;
    };
    audio.onended = () => {
      if (currentAudio === audio) currentAudio = null;
      resolve();
    };
    audio.onerror = () => {
      if (currentAudio === audio) currentAudio = null;
      maybeFallbackFromAudio(text, mode, runId, playbackStarted);
      resolve();
    };
    audio.play().catch(() => {
      if (currentAudio === audio) currentAudio = null;
      maybeFallbackFromAudio(text, mode, runId, playbackStarted);
      resolve();
    });
  });
}

function maybeFallbackFromAudio(text, mode, runId, playbackStarted) {
  if (playbackStarted || runId !== speechRunId) return;
  const voice = resolveSelectedVoice();
  const canUseSelectedWomanVoice = voice && femaleVoiceNames.test(voice.name) && !maleVoiceNames.test(voice.name);
  if (state.voiceProfile === "woman" && !canUseSelectedWomanVoice && state.language !== "ar") return;
  speakWithSpeechSynthesis(text, mode);
}

function getAudioTtsUrl(text) {
  const profile = audioTtsProfiles[state.language];
  if (!profile) return "";
  const query = encodeURIComponent(text.slice(0, 190));
  return `https://translate.google.com/translate_tts?ie=UTF-8&client=tw-ob&tl=${encodeURIComponent(profile.language)}&q=${query}`;
}

function getSpeechText(label) {
  const displayText = translate(label).trim();
  const languageOverrides = speechTextOverrides[state.language] || {};
  return languageOverrides[label] || languageOverrides[displayText] || displayText;
}

function createSpeechUtterance(text, mode = "word") {
  const utterance = new SpeechSynthesisUtterance(text);
  const profile = voiceProfiles[state.voiceProfile] || voiceProfiles.woman;
  const voice = resolveSelectedVoice();
  const tuning = getSpeechTuning(profile);
  utterance.volume = 1;
  utterance.rate = mode === "word" ? Math.max(0.82, tuning.rate - 0.02) : tuning.rate;
  utterance.pitch = tuning.pitch;

  utterance.lang = voice?.lang || speechLanguageFallbacks[state.language] || state.language;
  if (voice) utterance.voice = voice;
  return utterance;
}

function getSpeechTuning(profile) {
  if (state.language === "ar" && state.voiceProfile === "woman") {
    return { pitch: 1.55, rate: 0.8 };
  }
  if (state.language === "en-US" && state.voiceProfile === "man") {
    return { pitch: 0.78, rate: 0.88 };
  }
  if (state.language === "fr-FR" && state.voiceProfile === "woman") {
    return { pitch: 1.08, rate: 0.86 };
  }
  return { pitch: profile.pitch, rate: profile.rate };
}

function getMessageSpeechText() {
  return state.message.map((word) => getSpeechText(word.label)).join(" ");
}

function stopSpeech({ resetDuplicateMemory = true } = {}) {
  speechRunId += 1;
  if (resetDuplicateMemory) lastAudioSpeech = { key: "", time: 0 };
  if ("speechSynthesis" in window) window.speechSynthesis.cancel();
  if (currentAudio) {
    currentAudio.pause();
    currentAudio.currentTime = 0;
    currentAudio = null;
  }
  audioQueue = Promise.resolve();
  warmupPending = false;
}

